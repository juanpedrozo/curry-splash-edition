CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL CHECK (btrim(nome) <> ''),
    email VARCHAR(254) NOT NULL UNIQUE CHECK (email = lower(btrim(email)) AND email <> ''),
    senha_hash VARCHAR(100) NOT NULL,
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Os registros anteriores ao login são preservados. Somente o operador do banco
-- pode vinculá-los a uma conta existente com database/vincular-legado.sql.
ALTER TABLE jogadores ADD COLUMN usuario_id BIGINT REFERENCES usuarios(id) ON DELETE RESTRICT;
CREATE INDEX idx_jogadores_usuario_nome ON jogadores (usuario_id, nome, id);
