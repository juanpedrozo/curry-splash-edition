CREATE TABLE jogadores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL CONSTRAINT jogador_nome_valido CHECK (btrim(nome) <> ''),
    apelido VARCHAR(60),
    posicao VARCHAR(30),
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE treinos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    jogador_id BIGINT NOT NULL REFERENCES jogadores(id) ON DELETE CASCADE,
    data_treino DATE NOT NULL,
    duracao_minutos INTEGER NOT NULL CONSTRAINT treino_duracao_positiva CHECK (duracao_minutos > 0),
    observacoes TEXT,
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE arremessos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    treino_id BIGINT NOT NULL REFERENCES treinos(id) ON DELETE CASCADE,
    zona VARCHAR(30) NOT NULL CONSTRAINT arremesso_zona_valida CHECK (
        zona IN ('CANTO_ESQUERDO', 'ALA_ESQUERDA', 'TOPO_DO_ARCO', 'ALA_DIREITA', 'CANTO_DIREITO')
    ),
    tentativas INTEGER NOT NULL CONSTRAINT arremesso_tentativas_validas CHECK (tentativas >= 0),
    acertos INTEGER NOT NULL CONSTRAINT arremesso_acertos_validos CHECK (acertos BETWEEN 0 AND tentativas),
    CONSTRAINT arremesso_treino_zona_unica UNIQUE (treino_id, zona)
);

CREATE INDEX treino_jogador_data_idx ON treinos (jogador_id, data_treino DESC, id DESC);
CREATE INDEX treino_data_idx ON treinos (data_treino DESC, id DESC);
